import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
export function windowTokens(source) {
  const light = source.match(/:root \{[\s\S]*?\n\}/)?.[0];
  const dark = source.match(/\.dark \{[\s\S]*?\n\}/)?.[0];
  if (!light || !dark || !light.includes("--radius:"))
    throw new Error("Missing approved shadcn theme");
  return `/* Generated by scripts/sync-window-theme.mjs from ui/src/index.css. Do not edit. */
@font-face { font-family: "Geist Variable"; font-style: normal; font-weight: 100 900; font-display: swap; src: url("/fonts/Geist-latin-var.woff2") format("woff2"); }
${light}
${dark}
:root {
  --bg: var(--background); --ink: var(--foreground); --mute: var(--muted-foreground);
  --faint: var(--muted-foreground); --line: var(--border); --chip: var(--muted); --hover: var(--accent);
  --mark: #e53c1f; --ok: #276749; --bad: #b42318; --warning: #9a6700;
  --rules: var(--chart-1); --input-c: #3f6b4a; --loop: #a15c2a; --format: #5a4d7a;
  --font: "Geist Variable", ui-sans-serif, system-ui, sans-serif;
  --r: calc(var(--radius) * 1.4); --r-sm: calc(var(--radius) * .8); --r-lg: calc(var(--radius) * 1.8); --r-pill: 999px;
  --focus-ring: var(--ring); --s-1: 4px; --s-2: 8px; --s-3: 12px; --s-4: 16px; --s-5: 24px;
  --ease: cubic-bezier(.2,.7,.2,1); color-scheme: light;
}
.dark { --ok: #86d6a0; --bad: #ff958d; --warning: #e9b960; color-scheme: dark; }
`;
}
const source = readFileSync(new URL("ui/src/index.css", root), "utf8");
const dest = new URL("web/tokens.css", root);
const expected = windowTokens(source);
if (process.argv.includes("--check")) {
  if (readFileSync(dest, "utf8") !== expected)
    throw new Error(
      "Window tokens drifted: run node scripts/sync-window-theme.mjs",
    );
} else if (process.argv[1] === fileURLToPath(import.meta.url))
  writeFileSync(dest, expected);
