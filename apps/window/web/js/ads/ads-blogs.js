// Blogs & destinations.
//
// The question this screen answers is not "which article got the most traffic".
// It is "which articles are worth sending paid traffic to, and what do we
// actually know about what happened next". That question has three traps, and
// the screen is built around refusing all three:
//
// 1. Organic and paid arrive at the same URL as different populations. A
//    blended session count hides the fact that only one of them was bought, so
//    the switch re-scopes every counter the site splits by source and the split
//    is printed under the number rather than averaged away.
// 2. A provider cost and an observed outcome are different facts. They never
//    share a column, a total or a label, and cost per qualified lead is named
//    as the join it is.
// 3. An article that was read and an article that caused a signup are not the
//    same claim. UTMs identify which article a session landed on; they do not
//    prove the article caused anything, so no row here says "generated".
//
// The reader supplies article totals plus a two-way split by traffic source.
// Nothing is derived that the reader did not observe: a missing number renders
// as a dash, never as a zero.
//
// The one thing worth knowing before reading the code: every counter on this
// screen that could be scoped to a traffic source is scoped in exactly one
// place — `viewSessions` and `viewOnwardClicks`. Everything else reads article
// totals and says so, because the reader does not split it.

