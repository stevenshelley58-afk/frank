  /**
   * `segmented()` replaces its buttons on every render, which would drop
   * keyboard focus to the page body after an arrow-key change. Tagging the
   * buttons lets the renderer put focus back on the segment just chosen.
   */
  function taggedSegmented(groupName, options, activeId, onSelect, label) {
    const group = segmented(options, activeId, onSelect, { label });
    group.dataset.segmentGroup = groupName;
    group.querySelectorAll(".ads-segment").forEach((node_, index) => {
      node_.dataset.segment = options[index].id;
    });
    return group;
  }

  function restoreSegmentFocus(groupName, id) {
    // Queued as a microtask because `segmented` focuses its own (now detached)
    // button *after* calling onSelect; without the queue the restore is undone
    // by that call.
    queueMicrotask(() => content.querySelector(`[data-segment-group="${groupName}"] [data-segment="${id}"]`)?.focus());
  }

  function summaryOf(rows) {
    const sessions = sumOrNull(rows.map(viewSessions));
    const engaged = sumOrNull(rows.map((row) => metricInput(row).engagedSessions));
    const leads = sumOrNull(rows.map((row) => num(totalsOf(row).qualifiedLeads)));
    return {
      sessions,
      engaged,
      onward: sumOrNull(rows.map(viewOnwardClicks)),
      conversions: sumOrNull(rows.map((row) => num(totalsOf(row).siteConversions))),
      leads,
      // Only promoted articles carry provider cost. An article with no ad adds
      // nothing to this total, but it is not a zero-cost article either.
      spend: sumOrNull(rows.map(promotedSpend)),
      engagementRate: divide(engaged, sessions),
      costPerQualifiedLead: divide(sumOrNull(rows.map(promotedSpend)), leads),
      promoted: rows.filter((row) => row?.promoted === true).length,
    };
  }

