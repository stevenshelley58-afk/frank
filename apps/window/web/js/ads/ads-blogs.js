  function buildGroups(rows, currency) {
    const buckets = new Map();
    for (const row of rows) {
      const key = groupKeyFor(row, state.dimension);
      if (!buckets.has(key.id)) buckets.set(key.id, { id: key.id, label: key.label, note: key.note, rows: [] });
      buckets.get(key.id).rows.push(row);
    }
    return Array.from(buckets.values()).map((bucket) => {
      const totals = bucket.rows.map(totalsOf);
      const leads = sumOrNull(totals.map((t) => num(t.qualifiedLeads)));
      const spend = sumOrNull(bucket.rows.map(promotedSpend));
      const sessionTotal = sumOrNull(totals.map((t) => num(t.siteSessions)));
      return {
        id: bucket.id,
        label: bucket.label,
        note: bucket.note,
        count: bucket.rows.length,
        promoted: bucket.rows.filter((row) => row?.promoted === true).length,
        rows: bucket.rows,
        sessions: sumOrNull(bucket.rows.map(viewSessions)),
        onward: sumOrNull(bucket.rows.map(viewOnwardClicks)),
        leads,
        spend,
        costPerQualifiedLead: divide(spend, leads),
        // Evidence is judged on the article totals, not on the traffic view:
        // qualified leads are not split by source, so a source-scoped
        // denominator would compare two different populations.
        evidence: evidenceFor({ results: leads, linkClicks: sessionTotal, spend }, { metric: "results" }),
      };
    });
  }

